-- Library Management System: tables and starter data
-- Run this script once in Oracle APEX > SQL Workshop > SQL Scripts.

CREATE TABLE lms_books (
  book_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title         VARCHAR2(200) NOT NULL,
  author        VARCHAR2(150) NOT NULL,
  category       VARCHAR2(80),
  isbn           VARCHAR2(30) UNIQUE,
  total_copies   NUMBER DEFAULT 1 NOT NULL CHECK (total_copies >= 0),
  available_copies NUMBER DEFAULT 1 NOT NULL CHECK (available_copies >= 0),
  created_at     DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT lms_book_copies_ck CHECK (available_copies <= total_copies)
);

CREATE TABLE lms_members (
  member_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name    VARCHAR2(150) NOT NULL,
  email        VARCHAR2(200),
  phone        VARCHAR2(20),
  joined_on    DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE lms_issues (
  issue_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id        NUMBER NOT NULL REFERENCES lms_books(book_id),
  member_id      NUMBER NOT NULL REFERENCES lms_members(member_id),
  issue_date     DATE DEFAULT SYSDATE NOT NULL,
  due_date       DATE NOT NULL,
  return_date    DATE,
  fine_amount    NUMBER(10,2) DEFAULT 0 NOT NULL,
  status         VARCHAR2(10) DEFAULT 'ISSUED' NOT NULL
                 CHECK (status IN ('ISSUED','RETURNED')),
  CONSTRAINT lms_return_dates_ck CHECK (return_date IS NULL OR return_date >= issue_date)
);

